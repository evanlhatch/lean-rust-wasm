//! THE LIFECYCLE DIFFERENTIAL — the implementation's behavior against
//! the model `Machines.HostLifecycle` (the Lean `machine!` declaration;
//! `Machines.HostLifecycle.hostLifecycleTrans_pin` is the table's
//! source of record). The evidence level is the DIFFERENTIAL (03 §3,
//! tested agreement — never a theorem):
//!
//! 1. THE LEGAL ROWS — every row of [`MODEL_TRANS`] (the mirror of the
//!    model's table) is driven through the REAL host: the four driven
//!    transitions as method calls, the four refusal transitions by
//!    sabotage (tampered artifacts, invalid bytes, wrong signature, a
//!    trapping guest). Each row's landing phase must equal the model's.
//! 2. THE ILLEGAL PAIRS — every (event, from) NOT in the table refuses
//!    with the TYPED `HostError::Lifecycle` and leaves the phase
//!    unchanged (the phase-guard discipline, swept).
//! 3. THE JOURNAL DISCIPLINE — the Live loop's crash honesty: a crash
//!    after the journal effect (before any acknowledgement) recovers
//!    on reopen; a proposal that never committed leaves NO trace; a
//!    torn tail recovers to the last good frame AND reports the cut.
//! 4. THE COMMIT DUEL — the live loop verdict-for-verdict against the
//!    Lean checker's committed expectations.
//!
//! Mandatory negative controls: the clean journal reports NO recovery
//! (the torn-tail tooth does not fire on clean logs); the committed
//! artifacts pass the happy path (the refusal teeth are not vacuously
//! wide); the duel's verdict is exercised at its refuse rows (the
//! committed manifest's `refuse` expectations genuinely refuse).

