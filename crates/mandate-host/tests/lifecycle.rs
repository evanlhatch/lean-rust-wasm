fn committed_dir() -> PathBuf {
    mandate_host::repo_gen_dir()
}

/// A fresh per-test copy of the committed component artifact set (the
/// tamper teeth mutate their copy, never the committed universe).
fn scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "mandate-host-lifecycle-{}-{name}",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("scratch dir");
    let committed = committed_dir();
    for f in [
        "component-slice.wasm",
        "component-slice.wasm.hdr",
        "component-slice.wit",
    ] {
        fs::copy(committed.join(f), dir.join(f)).expect("copy the committed artifact");
    }
    dir
}

/// A scratch dir carrying `wasm_bytes` as the component artifact, with
/// a FRESH sidecar computed over exactly those bytes (the hash tie
/// passes — the tie proves identity, not correctness — so the bytes
/// reach the engine and the ENGINE's refusal is what the differential
/// observes).
fn doctored_scratch(name: &str, wasm_bytes: &[u8]) -> PathBuf {
    let dir = scratch(name);
    fs::write(dir.join("component-slice.wasm"), wasm_bytes).expect("write the doctored bytes");
    let sidecar = format!(
        "// GENERATED by componentgen (lean-4.33.0) at - — DO NOT EDIT\n\
         // spec test | Guest.Component | 1 item(s) | content hash {} | regen: just gen\n",
        bytes_hash(wasm_bytes)
    );
    fs::write(dir.join("component-slice.wasm.hdr"), sidecar).expect("write the fresh sidecar");
    dir
}

/// Invalid component bytes: the committed component's MAGIC corrupted
/// (the tie passes; the engine refuses — refuseInstantiate's face).
fn invalid_component_bytes() -> Vec<u8> {
    let mut wasm = fs::read(committed_dir().join("component-slice.wasm")).expect("read");
    wasm[0] ^= 0xff;
    wasm
}

/// A VALID component carrying `add64` with the WRONG component RESULT
/// type (`string`, not `u64`) — the surface check passes (the arity is
/// the params' count: `add64/2`), the engine instantiates, and the
/// start-time typed lift refuses (refuseStart's face — the signature
/// teeth live at the lift, past the skew fail-fast's arity surface).
fn wrong_signature_bytes() -> Vec<u8> {
    let wat = r#"(component
  (core module $m
    (memory (export "memory") 1)
    (func (export "canonical_abi_realloc") (param i32 i32 i32 i32) (result i32) i32.const 1024)
    (type $core_add (func (param i64 i64) (result i32)))
    (func (type $core_add) (param i64 i64) (result i32) i32.const 1024)
    (export "add64" (func 1)))
  (core instance $i (instantiate $m))
  (alias core export $i "memory" (core memory $mem))
  (alias core export $i "canonical_abi_realloc" (core func $realloc))
  (type $t (func (param "a" u64) (param "b" u64) (result string)))
  (func $f (type $t) (canon lift (core func $i "add64") (memory $mem) (realloc $realloc)))
  (export "add64" (func $f)))"#;
    wat::parse_str(wat).expect("the wrong-sig component builds")
}

/// A VALID, correctly-signed `add64` that TRAPS on call (the model's
/// `trap` face).
fn trapping_bytes() -> Vec<u8> {
    let wat = r#"(component
  (core module $m (type (func (param i64 i64) (result i64)))
    (func (type 0) (param i64 i64) (result i64) unreachable)
    (export "add64" (func 0)))
  (core instance $i (instantiate $m))
  (type $t (func (param "a" u64) (param "b" u64) (result u64)))
  (func $f (type $t) (canon lift (core func $i "add64")))
  (export "add64" (func $f)))"#;
    wat::parse_str(wat).expect("the trapping component builds")
}

/// The tampered fixture (a flipped byte — the load-time hash tie
/// refuses): the Failed phase's construction site.
fn tampered_scratch(name: &str) -> PathBuf {
    let dir = scratch(name);
    let p = dir.join("component-slice.wasm");
    let mut wasm = fs::read(&p).expect("read");
    let last = wasm.len() - 1;
    wasm[last] ^= 0xff;
    fs::write(&p, wasm).expect("write");
    dir
}

/// A host driven TO the given phase (the sweep's fixture). `Failed`
/// rides the tampered-load path (the model's `refuseLoad`).
fn host_at(phase: Phase) -> HostMachine {
    let mut h = HostMachine::new();
    match phase {
        Phase::Unloaded => {}
        Phase::Loaded => {
            h.load(&committed_dir()).expect("load the committed set");
        }
        Phase::Instantiated => {
            h.load(&committed_dir()).expect("load");
            h.instantiate().expect("instantiate");
        }
        Phase::Running => {
            h.load(&committed_dir()).expect("load");
            h.instantiate().expect("instantiate");
            h.start().expect("start");
        }
        Phase::Stopped => {
            h.load(&committed_dir()).expect("load");
            h.instantiate().expect("instantiate");
            h.start().expect("start");
            h.stop().expect("stop");
        }
        Phase::Failed => {
            let dir = tampered_scratch("host-at-failed");
            h.load(&dir).expect_err("the tampered load refuses");
        }
    }
    assert_eq!(
        h.phase(),
        phase,
        "the fixture must land exactly at {phase:?}"
    );
    h
}

/// THE HAPPY PATH (and the refusal teeth's negative control): the
/// committed artifact set drives the FULL lifecycle — every phase
/// lands exactly where the model's table says.
#[test]
fn happy_path_lands_each_model_row() {
    let mut h = HostMachine::new();
    assert_eq!(h.phase(), Phase::Unloaded);
    h.load(&committed_dir()).expect("load");
    assert_eq!(h.phase(), Phase::Loaded);
    h.instantiate().expect("instantiate");
    assert_eq!(h.phase(), Phase::Instantiated);
    h.start().expect("start");
    assert_eq!(h.phase(), Phase::Running);
    let got = h.call(2, 3).expect("the golden call");
    assert_eq!(got, GUEST_GOLDEN);
    assert_eq!(
        h.phase(),
        Phase::Running,
        "the call is running's activity, not a transition"
    );
    h.stop().expect("stop");
    assert_eq!(h.phase(), Phase::Stopped);
}

/// THE LEGAL ROWS, driven: each of the four driven transitions from
/// its model `from`-phase lands the host at the model's `to`-phase.
#[test]
fn the_driven_rows_agree_with_the_model() {
    for (event, from, to) in MODEL_TRANS {
        // The refusal rows are ENVIRONMENT-INDUCED (no method drives
        // them) — the_differential pins them via sabotage in
        // `the_refusal_rows_agree_with_the_model`.
        if !matches!(
            *event,
            EVENT_LOAD | EVENT_INSTANTIATE | EVENT_START | EVENT_STOP
        ) {
            continue;
        }
        let mut h = host_at(*from);
        let result = match *event {
            EVENT_LOAD => h.load(&committed_dir()),
            EVENT_INSTANTIATE => h.instantiate(),
            EVENT_START => h.start(),
            EVENT_STOP => h.stop(),
            _ => unreachable!("filtered above"),
        };
        assert!(
            result.is_ok(),
            "{event} from {from:?} must drive: {result:?}"
        );
        assert_eq!(
            h.phase(),
            *to,
            "{event}: the landing phase must be the model's"
        );
    }
}

/// THE REFUSAL ROWS, induced: each refusal transition's terminal face
/// is `Failed` — the escape path is an EXPLICIT transition (03 §4),
/// and the typed error surfaces.
#[test]
fn the_refusal_rows_agree_with_the_model() {
    // refuseLoad: unloaded → failed — the tampered artifact set (the
    // load-time hash tie refuses).
    let mut h = HostMachine::new();
    let dir = tampered_scratch("refuse-load");
    let err = h.load(&dir).expect_err("refuseLoad");
    assert!(
        matches!(err, HostError::ContentHashMismatch { .. }),
        "{err:?}"
    );
    assert_eq!(h.phase(), Phase::Failed);

    // refuseInstantiate: loaded → failed — hash-tied bytes the engine
    // refuses to compile.
    let mut h = HostMachine::new();
    let dir = doctored_scratch("refuse-instantiate", &invalid_component_bytes());
    h.load(&dir)
        .expect("the doctored set loads (the tie passes)");
    assert_eq!(h.phase(), Phase::Loaded);
    let err = h.instantiate().expect_err("refuseInstantiate");
    assert!(matches!(err, HostError::EngineRefused(_)), "{err:?}");
    assert_eq!(h.phase(), Phase::Failed);

    // refuseStart: instantiated → failed — a valid component whose
    // export's signature drifts from the world's contract.
    let mut h = HostMachine::new();
    let dir = doctored_scratch("refuse-start", &wrong_signature_bytes());
    h.load(&dir).expect("load");
    h.instantiate()
        .expect("the wrong-sig component instantiates");
    let err = h.start().expect_err("refuseStart");
    assert!(matches!(err, HostError::ComponentSignature(_)), "{err:?}");
    assert_eq!(h.phase(), Phase::Failed);

    // trap: running → failed — a valid, correctly-signed export that
    // traps on call.
    let mut h = HostMachine::new();
    let dir = doctored_scratch("trap", &trapping_bytes());
    h.load(&dir).expect("load");
    h.instantiate().expect("instantiate");
    h.start().expect("start");
    let err = h.call(2, 3).expect_err("trap");
    assert!(matches!(err, HostError::Engine(_)), "{err:?}");
    assert_eq!(h.phase(), Phase::Failed);
}

/// THE ILLEGAL-PAIR SWEEP: every (event, from) NOT in the model's
/// table refuses TYPED (`HostError::Lifecycle` — the model's legality
/// made a type error) and leaves the phase UNCHANGED. The sweep is
/// total over the driven events × the phases, minus the legal rows.
#[test]
fn every_illegal_pair_refuses_typed_and_stays_put() {
    for from in Phase::ALL {
        for event in [EVENT_LOAD, EVENT_INSTANTIATE, EVENT_START, EVENT_STOP] {
            let legal = MODEL_TRANS
                .iter()
                .any(|(e, f, _)| *e == event && *f == from);
            if legal {
                continue;
            }
            let mut h = host_at(from);
            let result = match event {
                EVENT_LOAD => h.load(&committed_dir()),
                EVENT_INSTANTIATE => h.instantiate(),
                EVENT_START => h.start(),
                EVENT_STOP => h.stop(),
                _ => unreachable!("the driven events are enumerated"),
            };
            match result {
                Err(HostError::Lifecycle { from: f, event: e }) => {
                    assert_eq!(f, from.name(), "the error names the phase it refused");
                    assert_eq!(e, event);
                }
                other => panic!(
                    "{event} from {from:?}: expected the typed Lifecycle refusal, got {other:?}"
                ),
            }
            assert_eq!(
                h.phase(),
                from,
                "an illegal transition never moves the host"
            );
        }
    }
}

