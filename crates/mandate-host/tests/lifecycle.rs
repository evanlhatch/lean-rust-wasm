// ── The journal discipline: the Live loop's crash honesty ──────────

fn journal_scratch(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "mandate-host-liverec-{}-{name}",
        std::process::id()
    ));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).expect("scratch dir");
    dir
}

/// The ledger row in the journal's field order (tid/src/dst/amount).
fn ledger_row(tid: u64, src: u64, dst: u64, amount: u64) -> mandate_delta::Row {
    mandate_delta::Row::build(
        &ledger_schema(),
        vec![
            Value::U64(tid),
            Value::U64(src),
            Value::U64(dst),
            Value::U64(amount),
        ],
    )
    .expect("the ledger row matches its own schema")
}

/// CRASH HONESTY, the mid-lifecycle cut: the commit's journal effect
/// landed (append + fsync — `Journal::record` returned), then the
/// process died BEFORE the acknowledgement (the in-memory apply, the
/// caller's verdict — simulated here by writing the journal DIRECTLY
/// and dropping everything). Recovery is honest: the durable log IS
/// the truth, and reopen reconstructs the full live state — the
/// transfer in the ledger, the balances moved, the version bumped.
#[test]
fn crash_after_the_journal_effect_recovers_honestly() {
    let dir = journal_scratch("crash-after-effect");
    let path = dir.join("journal.bin");
    {
        // The effect lands; the process "dies" before ANYTHING else.
        let mut j = mandate_host::Journal::open(&path, ledger_schema()).expect("open");
        j.record(Delta::Insert(ledger_row(7, 1, 2, 10)))
            .expect("the durable effect");
    }
    let live = Live::open(&path).expect("the reopen recovers the durable log");
    assert_eq!(
        live.version(),
        2,
        "the accepted commit's version bump survives the crash"
    );
    assert_eq!(
        live.transfers().len(),
        1,
        "the journaled transfer IS in the ledger"
    );
    assert_eq!(
        live.accounts(),
        &[
            Account {
                id: 1,
                owner: "alice".into(),
                balance: 90
            },
            Account {
                id: 2,
                owner: "bob".into(),
                balance: 60
            },
        ],
        "the balances moved: the derived state replays the durable effect"
    );
}

/// CRASH HONESTY, the other face: a PROPOSAL that never committed
/// (crash between propose and commit) leaves NO durable trace — the
/// reopen must NOT resurrect work that was never authorized. The
/// journal carries accepted effects, not intentions.
#[test]
fn a_proposal_that_never_committed_leaves_no_trace() {
    let dir = journal_scratch("crash-before-commit");
    let path = dir.join("journal.bin");
    {
        let live = Live::open(&path).expect("fresh");
        let p = live.propose(9, 1, 2, 25);
        // The proposal is computed... and the process dies. No commit,
        // no journal entry — `p` is pure data (a Copy), the point.
        let _ = p;
    }
    let live = Live::open(&path).expect("reopen");
    assert_eq!(live.version(), 1, "no accepted commit — no bump");
    assert!(
        live.transfers().is_empty(),
        "no journaled intent — the proposal is gone"
    );
    assert!(live.violations().is_empty());
    assert_eq!(
        live.accounts(),
        &[
            Account {
                id: 1,
                owner: "alice".into(),
                balance: 100
            },
            Account {
                id: 2,
                owner: "bob".into(),
                balance: 50
            },
        ],
        "the fixture state, untouched"
    );
}

/// THE TORN TAIL: a crash MID-APPEND (half a frame on disk) recovers
/// to the last good frame — and the cut is REPORTED (the recovery
/// report is data, never silence). The good prefix's commits survive.
#[test]
fn a_torn_tail_recovers_to_the_last_good_frame_and_reports() {
    let dir = journal_scratch("torn-tail");
    let path = dir.join("journal.bin");
    {
        let mut live = Live::open(&path).expect("fresh");
        let p1 = live.propose(1, 1, 2, 10);
        assert!(matches!(
            live.commit(&p1),
            Ok(mandate_host::LiveVerdict::Committed { .. })
        ));
        let p2 = live.propose(2, 2, 1, 5);
        assert!(matches!(
            live.commit(&p2),
            Ok(mandate_host::LiveVerdict::Committed { .. })
        ));
    }
    // The crash mid-append: half of a VALID next frame hits the disk.
    let mut bytes = fs::read(&path).expect("read the journal");
    let mut frame = Vec::new();
    assert!(
        mandate_delta::delta::enc_delta(
            &ledger_schema(),
            &Delta::Insert(ledger_row(3, 1, 2, 1)),
            &mut frame
        ),
        "the delta encodes"
    );
    bytes.extend_from_slice(&frame[..frame.len() / 2]);
    fs::write(&path, bytes).expect("write the torn journal");

    let live = Live::open(&path).expect("the recovering open refuses nothing here");
    let recovery = live.recovery().expect("the cut is REPORTED, never silent");
    assert!(
        recovery.frames == 2,
        "the good prefix carries the two commits"
    );
    assert_eq!(live.version(), 3, "the version rides the good prefix");
    assert_eq!(live.transfers().len(), 2);
    // The torn transfer is NOT in the recovered state (it never
    // completely landed — the honest recovery does not invent it).
    assert!(live.transfers().iter().all(|t| t.tid != 3));
}

/// THE REOPEN TOOTH (the Live loop's invariant, pinned): the
/// in-memory state is EXACTLY the journal's replay over the fixture —
/// commit N transfers, reopen, compare the full state.
#[test]
fn reopen_equivalence_the_state_is_the_journal_replay() {
    let dir = journal_scratch("reopen-equivalence");
    let path = dir.join("journal.bin");
    let committed: Vec<(u64, u64, u64, u64)> = vec![(1, 1, 2, 10), (2, 2, 1, 5), (3, 1, 2, 7)];
    let end_accounts: Vec<Account>;
    {
        let mut live = Live::open(&path).expect("fresh");
        for (tid, src, dst, amt) in &committed {
            let p = live.propose(*tid, *src, *dst, *amt);
            assert!(matches!(
                live.commit(&p),
                Ok(mandate_host::LiveVerdict::Committed { .. })
            ));
        }
        end_accounts = live.accounts().to_vec();
        assert_eq!(live.version(), 1 + committed.len() as u64);
    }
    let live = Live::open(&path).expect("reopen");
    assert_eq!(live.version(), 1 + committed.len() as u64);
    assert_eq!(live.transfers().len(), committed.len());
    assert_eq!(
        live.accounts(),
        &end_accounts,
        "the reopen reconstructs the same state"
    );
}

/// THE STALENESS TOOTH (the race-honesty carrier, pinned beside the
/// crash tests): a proposal computed at version 1 refused by a commit,
/// then resubmitted against a moved base REFUSES on the version —
